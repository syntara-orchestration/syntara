"""Separate Git requirements from hash-checked packages for Hermeto prefetch."""

from __future__ import annotations

import re
import sys
from pathlib import Path


def split_vcs_requirements(requirements: Path) -> None:
    """Partition an exported manifest; Hermeto checks hash mode per file."""
    packages: list[str] = []
    vcs = ["# Generated by make sync-requirements; Git revisions are pinned in uv.lock.\n"]
    in_vcs = False
    for line in requirements.read_text().splitlines(keepends=True):
        if line and not line[0].isspace() and not line.startswith("#"):
            in_vcs = bool(re.match(r"[A-Za-z0-9_.-]+(?:\[[^]]+\])?\s*@\s*git\+", line))
        (vcs if in_vcs else packages).append(line)
    requirements.write_text("".join(packages))
    requirements.with_name("requirements-vcs.txt").write_text("".join(vcs))


if __name__ == "__main__":
    split_vcs_requirements(Path(sys.argv[1] if len(sys.argv) > 1 else "requirements.txt"))
